#!/usr/bin/env bash
#
# 容器内完整验证流水线：静态检查 → 单元测试 → 端到端验证。
# 由 Dockerfile 的 CMD 调用。
set -euo pipefail

cd "$(dirname "$0")/.."

echo "=========================================="
echo " 1/3  go vet"
echo "=========================================="
go vet ./...

echo
echo "=========================================="
echo " 2/3  go test"
echo "=========================================="
go test -count=1 ./...

echo
echo "=========================================="
echo " 3/3  端到端验证"
echo "=========================================="
export YSSH=/usr/local/bin/yssh
bash scripts/e2e.sh

echo
echo "=========================================="
echo " 全部验证通过"
echo "=========================================="
